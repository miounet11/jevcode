/** 按分类分组，组内按 stars 降序 */
export function projectsByCategory(): Array<{ category: Category; items: Project[] }> {
  return categories
    .map((category) => ({
      category,
      items: projects
        .filter((p) => p.category === category.key)
        .sort((a, b) => b.stars - a.stars),
    }))
    .filter((group) => group.items.length > 0);
}
